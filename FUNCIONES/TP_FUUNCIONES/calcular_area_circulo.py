def calcular_area_circulo(radio):
    pi = 3.14159
    area = pi * radio ** 2
    print(f"El área del círculo con radio {radio} es: {area}")

def calcular_perimetro_circulo(radio):
    pi = 3.14159
    perimetro = 2 * pi * radio
    print(f"El perímetro del círculo con radio {radio} es: {perimetro}")